def smooth_path(pts, tension=0.5):
    """Closed Catmull-Rom spline -> cubic Bezier path; 's' points keep sharp corners."""
    P = [(p[0], p[1], len(p) > 2) for p in pts]
    n = len(P); out = f"M{P[0][0]} {P[0][1]}"
    for i in range(n):
        p0, p1, p2, p3 = P[i - 1], P[i], P[(i + 1) % n], P[(i + 2) % n]
        k1 = 0 if p1[2] else tension / 3 * 2 * .75
        k2 = 0 if p2[2] else tension / 3 * 2 * .75
        c1 = (p1[0] + (p2[0] - p0[0]) * k1 / 2, p1[1] + (p2[1] - p0[1]) * k1 / 2)
        c2 = (p2[0] - (p3[0] - p1[0]) * k2 / 2, p2[1] - (p3[1] - p1[1]) * k2 / 2)
        out += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]} {p2[1]}"
    return out + "Z"

